revoke all on public.membros, public.campanhas, public.criativos, public.metricas, public.comentarios, public.ajustes from anon;
grant select, insert, update, delete on public.membros, public.campanhas, public.criativos, public.metricas, public.comentarios to authenticated;
grant select, update on public.ajustes to authenticated;

