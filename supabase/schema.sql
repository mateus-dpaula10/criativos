-- Painel de Criativos: banco no Supabase (plano gratuito).
-- Rode este arquivo inteiro no SQL Editor do projeto (Database → SQL Editor → New query → Run).
-- Pode rodar de novo sem quebrar nada: tudo usa "if not exists" / "or replace" / "on conflict".
--
-- Segurança: só quem está na tabela "membros" (pelo e-mail da conta, já confirmado) lê ou grava
-- qualquer coisa. Quem só criou conta, sem ter sido adicionado, não vê nada. Só admin mexe na equipe.

-- ---------- Equipe ----------
create table if not exists public.membros (
  email text primary key check (email = lower(email) and position('@' in email) > 1),
  nome text not null default '',
  papel text not null default 'editor' check (papel in ('admin', 'editor', 'trafego')),
  criado_em timestamptz not null default now()
);

create or replace function public.email_atual() returns text
language sql stable set search_path = '' as $$
  select lower(coalesce(auth.jwt() ->> 'email', ''));
$$;

create or replace function public.eh_membro() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.membros m where m.email = public.email_atual());
$$;

create or replace function public.eh_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.membros m where m.email = public.email_atual() and m.papel = 'admin');
$$;

-- Permissão explícita (funciona mesmo com "Automatically expose new tables" desligado no projeto).
revoke execute on function public.email_atual(), public.eh_membro(), public.eh_admin() from public, anon;
grant execute on function public.email_atual(), public.eh_membro(), public.eh_admin() to authenticated;

-- ---------- Campanhas (abrigo/oferta/produto) ----------
create table if not exists public.campanhas (
  id uuid primary key default gen_random_uuid(),
  nome text not null check (length(nome) between 1 and 80),
  sigla text not null check (length(sigla) between 1 and 12),
  cor text not null default '#b42318' check (cor ~ '^#[0-9a-fA-F]{6}$'),
  ativa boolean not null default true,
  criado_em timestamptz not null default now()
);

-- ---------- Criativos ----------
create table if not exists public.criativos (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  campanha_id uuid references public.campanhas (id) on delete set null,
  parent_id uuid references public.criativos (id) on delete set null,
  titulo text not null check (length(titulo) between 1 and 160),
  etapa text not null default 'ideia'
    check (etapa in ('ideia', 'roteiro', 'gravacao', 'edicao', 'revisao', 'aprovado', 'no_ar', 'pausado')),
  veredito text check (veredito in ('teste', 'vencedor', 'perdedor')),
  angulo text not null default '' check (length(angulo) <= 80),
  formatos text[] not null default '{9x16}',
  ferramenta text not null default 'capcut' check (ferramenta in ('capcut', 'premiere', 'outra')),
  responsavel text,
  prazo date,
  duracao_s numeric(7, 2),
  link_arquivo text not null default '',
  link_projeto text not null default '',
  thumb_path text,
  roteiro jsonb not null default '[]'::jsonb,
  checklist jsonb not null default '{}'::jsonb,
  montagem jsonb,
  notas text not null default '' check (length(notas) <= 8000),
  tags text[] not null default '{}',
  criado_por text default public.email_atual(),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists criativos_etapa_idx on public.criativos (etapa);
create index if not exists criativos_campanha_idx on public.criativos (campanha_id);
create index if not exists criativos_parent_idx on public.criativos (parent_id);

create or replace function public.tocar_atualizado_em() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.atualizado_em := now();
  return new;
end;
$$;
drop trigger if exists criativos_atualizado_em on public.criativos;
create trigger criativos_atualizado_em before update on public.criativos
  for each row execute function public.tocar_atualizado_em();

-- ---------- Resultados (vindos do CSV do Gerenciador de Anúncios ou digitados) ----------
create table if not exists public.metricas (
  id uuid primary key default gen_random_uuid(),
  criativo_id uuid not null references public.criativos (id) on delete cascade,
  inicio date not null,
  fim date not null,
  gasto_cents bigint not null default 0 check (gasto_cents >= 0),
  impressoes bigint check (impressoes >= 0),
  cliques bigint check (cliques >= 0),
  views_3s bigint check (views_3s >= 0),
  thruplays bigint check (thruplays >= 0),
  resultados numeric(12, 2) check (resultados >= 0),
  receita_cents bigint check (receita_cents >= 0),
  fonte text not null default 'manual' check (fonte in ('manual', 'csv')),
  registrado_por text default public.email_atual(),
  registrado_em timestamptz not null default now(),
  check (fim >= inicio),
  unique (criativo_id, inicio, fim)
);
create index if not exists metricas_periodo_idx on public.metricas (inicio, fim);

-- Importação do CSV numa transação só: para os criativos do arquivo, apaga o que já havia no período
-- importado e grava as linhas novas (reimportar o mesmo relatório não duplica nada).
create or replace function public.importar_metricas(p_linhas jsonb, p_de date, p_ate date) returns integer
language plpgsql security invoker set search_path = '' as $$
declare
  n integer;
begin
  if not public.eh_membro() then
    raise exception 'sem permissão' using errcode = '42501';
  end if;
  delete from public.metricas m
   where m.criativo_id in (select (x ->> 'criativo_id')::uuid from jsonb_array_elements(p_linhas) x)
     and m.inicio <= p_ate and m.fim >= p_de;
  insert into public.metricas (criativo_id, inicio, fim, gasto_cents, impressoes, cliques, views_3s, thruplays, resultados, receita_cents, fonte)
  select r.criativo_id, r.inicio, r.fim, coalesce(r.gasto_cents, 0), r.impressoes, r.cliques, r.views_3s, r.thruplays, r.resultados, r.receita_cents, 'csv'
    from jsonb_to_recordset(p_linhas) as r (criativo_id uuid, inicio date, fim date, gasto_cents bigint, impressoes bigint,
      cliques bigint, views_3s bigint, thruplays bigint, resultados numeric, receita_cents bigint);
  get diagnostics n = row_count;
  return n;
end;
$$;
revoke execute on function public.importar_metricas(jsonb, date, date) from public, anon;
grant execute on function public.importar_metricas(jsonb, date, date) to authenticated;

-- ---------- Comentários de revisão ----------
create table if not exists public.comentarios (
  id uuid primary key default gen_random_uuid(),
  criativo_id uuid not null references public.criativos (id) on delete cascade,
  autor text not null default public.email_atual(),
  texto text not null check (length(texto) between 1 and 4000),
  criado_em timestamptz not null default now()
);
create index if not exists comentarios_criativo_idx on public.comentarios (criativo_id, criado_em);

-- ---------- Ajustes da equipe (uma linha só) ----------
create table if not exists public.ajustes (
  id smallint primary key default 1 check (id = 1),
  modelo_nome text not null default '{campanha}_{codigo}_{angulo}_{data}' check (position('{codigo}' in modelo_nome) > 0),
  pasta_clipes text not null default '',
  atualizado_em timestamptz not null default now()
);
insert into public.ajustes (id) values (1) on conflict (id) do nothing;

